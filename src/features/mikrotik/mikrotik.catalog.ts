export function getModel(id: string): MikrotikModel | undefined {
  return MIKROTIK_CATALOG.find((model) => model.id === id);
}

/** Total wired Ethernet ports (excluding SFP+). */
export function ethernetPortCount(model: MikrotikModel): number {
  const { fastEthernetPorts, gigabitPorts, multiGig2_5Ports } = model.ethernet;
  return fastEthernetPorts + gigabitPorts + multiGig2_5Ports;
}
